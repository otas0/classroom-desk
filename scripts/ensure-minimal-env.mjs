#!/usr/bin/env node
/**
 * Create repo-root .env for minimal classroom deploy if missing.
 * Zero prompts: strong secrets, HOST=0.0.0.0, Shield off, no TLS/DeskDNS/gateway.
 */
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { networkInterfaces } from 'node:os';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env');
const force = process.argv.includes('--force');

function lanIps() {
  const out = [];
  try {
    for (const list of Object.values(networkInterfaces())) {
      for (const n of list ?? []) {
        if (n.family !== 'IPv4' && n.family !== 4) continue;
        if (n.internal) continue;
        out.push(n.address);
      }
    }
  } catch {
    /* ignore */
  }
  return out;
}

function hex32() {
  return randomBytes(32).toString('hex');
}

if (fs.existsSync(envPath) && !force) {
  console.log(`[minimal-env] keep existing ${envPath}`);
} else {
  const body = `# Auto-generated by npm run ensure:minimal-env — Pilot 最小教室部署
# 勿提交仓库。重新生成: npm run ensure:minimal-env -- --force
# 进阶（网关/TLS/DeskDNS）见 docs/MINIMAL_DEPLOY.md

CLASSROOM_DESK_MINIMAL=1
JWT_SECRET=${hex32()}
AUDIT_HMAC_KEY=${hex32()}
HOST=0.0.0.0
PORT=8787
# Shield 保持未配置 = UI 诚实「网关未断」；校园网包再改 CLASSROOM_DESK_SHIELD
# 最高保密档默认关；本机 HTTP 即可上课（勿开 NODE_ENV=production+max_secrecy 除非已上 HTTPS）
TEACHER_USERNAME=teacher
# 首次启动若未设密码，服务端会打印生成的教师口令
`;
  fs.writeFileSync(envPath, body, { mode: 0o600 });
  console.log(`[minimal-env] wrote ${envPath}`);
}

const ips = lanIps();
const port = 8787;
console.log('');
console.log('=== 最小部署（无需网关 / TLS / DeskDNS）===');
console.log(`教师本机:  http://127.0.0.1:${port}/admin/`);
if (ips[0]) {
  console.log(`学生 apiBase: http://${ips[0]}:${port}`);
  for (const ip of ips.slice(1, 4)) {
    console.log(`             http://${ip}:${port}`);
  }
} else {
  console.log('学生 apiBase: http://<教师机局域网IP>:8787');
}
console.log('账号: teacher（首次启动看终端打印的口令，或设 TEACHER_PASSWORD）');
console.log('自检: npm run check:pilot-go-live -- --minimal');
console.log('');
